#!/usr/bin/env python3
"""Generate/check the human-readable maintained-file catalogue. Python stdlib only."""
from __future__ import annotations
import argparse
from pathlib import Path
import re
from urllib.parse import quote, unquote, urlsplit

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'docs/FILE_INDEX.md'
SKIP_DIRS = {'.git', '.dart_tool', '.idea', '.fvm', '.gradle', '.kotlin',
             '.symlinks', 'build', 'Pods', '.plugin_symlinks', 'ephemeral',
             '__pycache__', 'coverage', '.pub', '.pub-cache'}
SKIP_NAMES = {'.DS_Store', '.flutter-plugins-dependencies', 'local.properties',
              'GeneratedPluginRegistrant.java', 'GeneratedPluginRegistrant.h',
              'GeneratedPluginRegistrant.m', 'Generated.xcconfig',
              'flutter_export_environment.sh', '.last_build_id',
              'generated_plugin_registrant.dart'}


def maintained(path: Path) -> bool:
    parts = path.relative_to(ROOT).parts
    return (path.is_file() and not path.is_symlink()
            and not any(p in SKIP_DIRS for p in parts)
            and path.name not in SKIP_NAMES
            and path.suffix not in {'.pyc', '.iml'}
            and not path.name.startswith('.env')
            and path.name not in {'key.properties', 'keystore.properties'}
            and path.suffix not in {'.jks', '.keystore'})


def index_text() -> str:
    groups: dict[str, list[Path]] = {}
    for path in sorted(ROOT.rglob('*')):
        if path == OUTPUT or not maintained(path):
            continue
        rel = path.relative_to(ROOT)
        group = 'Root configuration' if len(rel.parts) == 1 else rel.parts[0] + '/'
        groups.setdefault(group, []).append(rel)
    lines = ['# Maintained file index', '',
             '[Demo guide](../README.md) · [Documentation](README.md)', '',
             'Generated by `python3 tools/project_index.py`. Search this page by filename, feature, gesture or extension. Build/cache files and local machine configuration are excluded. This index lists itself separately: [FILE_INDEX.md](FILE_INDEX.md).', '']
    for group, paths in sorted(groups.items()):
        lines += [f'## {group} ({len(paths)} files)', '']
        for path in paths:
            label = path.as_posix()
            lines.append(f'- [{label}](../{quote(label, safe="/._-")})')
        lines.append('')
    return '\n'.join(lines)


def broken_links() -> list[str]:
    # Current guides; historical Markdown contains original external-machine paths.
    current = [ROOT / 'README.md']
    current += list((ROOT / 'lib').rglob('README.md'))
    current += [ROOT / p for p in ('assets/README.md', 'android/README.md',
                'ios/README.md', 'web/README.md', 'test/README.md', 'tools/README.md')]
    current += [p for p in (ROOT / 'docs').glob('*.md') if p.name != 'VALIDATION.md']
    current += [ROOT / 'docs/design/README.md']
    errors = []
    for path in current:
        if not path.exists():
            continue
        for target in re.findall(r'\]\(([^)]+)\)', path.read_text()):
            target = target.strip().strip('<>')
            parsed = urlsplit(target)
            if parsed.scheme or not parsed.path:
                continue
            dest = path.parent / unquote(parsed.path)
            if not dest.exists():
                errors.append(f'{path.relative_to(ROOT)}: {target}')
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check freshness and local guide links without writing')
    args = parser.parse_args()
    text = index_text()
    if args.check:
        errors = broken_links()
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            errors.insert(0, 'docs/FILE_INDEX.md is stale: run python3 tools/project_index.py')
        if errors:
            print('\n'.join(errors))
            return 1
        print('File index is current; all local links in current guides resolve.')
    else:
        OUTPUT.write_text(text)
        print('Updated docs/FILE_INDEX.md')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
